#!/usr/bin/env bash
# Backing direct deployment (no containers).
#
# Run as root on the target host:
#   cd /home/yanxx/backing
#   bash install.sh
#
# Expected uploads in /home/yanxx/backing:
#   backing-source.tar.gz             source archive from the committed branch
#   stock_backtest.snapshot.db.gz     optional consistent SQLite snapshot
#   backend.env                       local backend/.env (contains AI keys)
#   install.sh                        this script
#
# The script installs a dedicated Python 3.12 environment (conda if the host
# Python is not 3.12), builds the frontend, restores the database snapshot,
# runs Alembic, and starts two systemd services:
#   backing-backend.service   API on 127.0.0.1:8808
#   backing-frontend.service  Vite preview on 0.0.0.0:5174 (proxies /api)

set -euo pipefail

ROOT="${ROOT:-/home/yanxx/backing}"
RUNTIME_ROOT="${RUNTIME_ROOT:-/opt/backing}"
ARCHIVE="${ARCHIVE:-$ROOT/backing-source.tar.gz}"
DB_GZ="${DB_GZ:-$ROOT/stock_backtest.snapshot.db.gz}"
ENV_SOURCE="${ENV_SOURCE:-$ROOT/backend.env}"
SRC="$ROOT/source"
VENV="$RUNTIME_ROOT/venv"
DATA="$ROOT/data"
ENV_FILE="$ROOT/config/backend.env"
REPLACE_DB="${REPLACE_DB:-0}"
SERVICE_USER="${SERVICE_USER:-yanxx}"

log() { printf '\n==> %s\n' "$*"; }
warn() { printf 'WARNING: %s\n' "$*" >&2; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "Run as root."
[ -f "$ARCHIVE" ] || die "Missing source archive: $ARCHIVE"
if [ ! -f "$ENV_SOURCE" ]; then
    warn "backend.env not found; generating a minimal configuration."
fi

log "Create directories"
mkdir -p "$ROOT/config" "$DATA/backend-data" "$ROOT/logs" "$RUNTIME_ROOT"
chown "$SERVICE_USER:$SERVICE_USER" "$RUNTIME_ROOT"

log "Extract source"
if [ -e "$SRC" ]; then
    previous="$SRC.prev.$(date +%Y%m%d%H%M%S)"
    mv "$SRC" "$previous"
    echo "Previous source moved to $previous"
fi
mkdir -p "$SRC"
tar -xzf "$ARCHIVE" -C "$SRC"
[ -f "$SRC/backend/main.py" ] || die "Unexpected archive layout."
[ -f "$SRC/frontend/package.json" ] || die "Frontend sources missing."

log "Write runtime configuration"
KRONOS_TOKEN=""
if [ -f /home/yanxx/kronos-service/service.env ]; then
    KRONOS_TOKEN="$(grep -E '^KRONOS_SERVICE_TOKEN=' /home/yanxx/kronos-service/service.env | head -n 1 | cut -d= -f2- || true)"
fi
export KRONOS_TOKEN

python3 - "$ENV_SOURCE" "$ENV_FILE" "$ROOT" <<'PY'
import os
import secrets
import sys
from pathlib import Path

source, target, root = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
values = {}
if source.exists():
    for raw in source.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()

if not values.get("API_KEY"):
    values["API_KEY"] = secrets.token_hex(32)
if not values.get("SESSION_SECRET"):
    values["SESSION_SECRET"] = secrets.token_hex(32)

values.setdefault("KLINE_PROVIDER", "baostock")
values.setdefault("STOCK_LIST_PROVIDER", "akshare")
values.setdefault("DEEPSEEK_BASE_URL", "https://api.deepseek.com/v1")
values.setdefault("DEEPSEEK_MODEL", "deepseek-v4-flash")
values.setdefault(
    "WATCHLIST_STOCKS",
    "sh.600000,sh.600519,sh.601318,sh.000001,sz.000001,sz.399001,sz.399006",
)
if os.environ.get("KRONOS_TOKEN"):
    values["KRONOS_SERVICE_TOKEN"] = os.environ["KRONOS_TOKEN"]

values.pop("BACKING_ENV_FILE", None)
values.update(
    {
        "APP_ENV": "development",
        "HOST": "127.0.0.1",
        "PORT": "8808",
        "DATABASE_URL": f"sqlite:///{root}/data/stock_backtest.db",
        "FRONTEND_ORIGIN": "http://172.22.226.86:5174",
        "CORS_ORIGINS": "http://172.22.226.86:5174,http://127.0.0.1:5174",
        "SESSION_HTTPS_ONLY": "false",
        "SESSION_SAMESITE": "lax",
        "AUTH_USERNAME": values.get("AUTH_USERNAME", "admin"),
        "TASK_BACKEND": "threads",
        "USE_PROXY": "false",
        "REALTIME_SNAPSHOT_PROVIDER": "tencent",
        "REALTIME_BARS_PROVIDER": "tencent",
        "KRONOS_SERVICE_URL": "http://172.22.226.86:8211",
    }
)

target.write_text(
    "# Generated by deploy/direct/install.sh. Edit and restart to apply.\n\n"
    + "\n".join(f"{key}={value}" for key, value in values.items())
    + "\n",
    encoding="utf-8",
)
PY
chmod 600 "$ENV_FILE"
chown "$SERVICE_USER:$SERVICE_USER" "$ENV_FILE"
echo "Runtime configuration written to $ENV_FILE (mode 600, owner $SERVICE_USER)."

log "Select Python 3.12"
PY=""
if command -v python3.12 >/dev/null 2>&1; then
    PY="$(command -v python3.12)"
elif [ -x /opt/miniconda3/bin/conda ]; then
    if [ ! -x "$RUNTIME_ROOT/py312/bin/python" ]; then
        /opt/miniconda3/bin/conda create -y -p "$RUNTIME_ROOT/py312" python=3.12
    fi
    PY="$RUNTIME_ROOT/py312/bin/python"
else
    PY="$(command -v python3)"
    warn "python3.12 not found; using $PY. Some pinned wheels may not install."
fi
"$PY" --version

log "Create virtualenv"
if [ ! -x "$VENV/bin/python" ]; then
    "$PY" -m venv "$VENV"
fi
"$VENV/bin/python" -m pip install --upgrade pip wheel

log "Install PyTorch (CPU)"
if ! "$VENV/bin/pip" install --index-url https://download.pytorch.org/whl/cpu "torch==2.13.0"; then
    warn "CPU wheel index failed; falling back to PyPI torch"
    "$VENV/bin/pip" install "torch==2.13.0"
fi

log "Install backend dependencies"
cd "$SRC/backend"
"$VENV/bin/pip" install -r requirements.txt
"$VENV/bin/pip" install --no-deps -e "$SRC/TradingAgents-astock"

log "Link runtime data"
if [ -e "$SRC/backend/data" ] && [ ! -L "$SRC/backend/data" ]; then
    mv "$SRC/backend/data" "$DATA/backend-data.initial.$(date +%s)"
fi
ln -sfn "$DATA/backend-data" "$SRC/backend/data"

log "Restore database snapshot"
if [ -f "$DB_GZ" ]; then
    if [ -e "$DATA/stock_backtest.db" ] && [ "$REPLACE_DB" != "1" ]; then
        echo "Existing database kept; set REPLACE_DB=1 to replace it."
    else
        gunzip -c "$DB_GZ" > "$DATA/stock_backtest.db"
        chmod 600 "$DATA/stock_backtest.db"
        chown "$SERVICE_USER:$SERVICE_USER" "$DATA/stock_backtest.db"
        echo "Database restored from snapshot."
    fi
else
    echo "No snapshot uploaded; an empty database will be created."
fi

log "Run migrations"
cd "$SRC/backend"
BACKING_ENV_FILE="$ENV_FILE" "$VENV/bin/alembic" upgrade head

log "Build frontend"
NPM="/usr/bin/npm"
if [ ! -x "$NPM" ]; then
    NPM="$(command -v npm || true)"
fi
if [ -z "$NPM" ]; then
    NPM="$(ls -1 /root/.nvm/versions/node/*/bin/npm 2>/dev/null | tail -n 1 || true)"
fi
[ -n "$NPM" ] || die "npm not found; install Node.js 18+ or add npm to PATH."
NODE_DIR="$(dirname "$NPM")"
"$NPM" --version
cd "$SRC/frontend"
"$NPM" ci
"$NPM" run build

log "Set service ownership"
chown -R "$SERVICE_USER:$SERVICE_USER" "$SRC" "$RUNTIME_ROOT" "$DATA" "$ROOT/config" 2>/dev/null || true
if command -v restorecon >/dev/null 2>&1; then
    restorecon -R "$ROOT" >/dev/null 2>&1 || true
    restorecon -R "$RUNTIME_ROOT" >/dev/null 2>&1 || true
fi

log "Install systemd services"
cat > /etc/systemd/system/backing-backend.service <<EOF
[Unit]
Description=Backing API (direct)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=$SERVICE_USER
Group=$SERVICE_USER
WorkingDirectory=$SRC/backend
Environment=BACKING_ENV_FILE=$ENV_FILE
ExecStart=$VENV/bin/python main.py
Restart=always
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF

cat > /etc/systemd/system/backing-frontend.service <<EOF
[Unit]
Description=Backing frontend preview (direct)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=$SERVICE_USER
Group=$SERVICE_USER
WorkingDirectory=$SRC/frontend
Environment=PATH=$NODE_DIR:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
ExecStart=$NPM run preview -- --host 0.0.0.0 --port 5174 --strictPort
Restart=always
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable backing-backend.service backing-frontend.service
systemctl restart backing-backend.service backing-frontend.service

log "Open firewall port 5174 if needed"
if command -v firewall-cmd >/dev/null 2>&1 && firewall-cmd --state >/dev/null 2>&1; then
    if ! firewall-cmd --query-port=5174/tcp >/dev/null 2>&1; then
        firewall-cmd --permanent --add-port=5174/tcp
        firewall-cmd --reload
    fi
fi

log "Health checks"
backend_ok=0
for _ in $(seq 1 30); do
    if curl -fsS http://127.0.0.1:8808/api/v1/health >/dev/null 2>&1; then
        backend_ok=1
        break
    fi
    sleep 2
done
if [ "$backend_ok" != "1" ]; then
    journalctl -u backing-backend -n 80 --no-pager
    die "Backend health check failed."
fi
curl -fsS http://127.0.0.1:8808/api/v1/health
echo

frontend_ok=0
for _ in $(seq 1 15); do
    code="$(curl -s -o /dev/null -w '%{http_code}' http://127.0.0.1:5174/ || true)"
    if [ "$code" = "200" ]; then
        frontend_ok=1
        break
    fi
    sleep 2
done
if [ "$frontend_ok" != "1" ]; then
    journalctl -u backing-frontend -n 80 --no-pager
    die "Frontend health check failed."
fi
echo "Frontend HTTP 200."

log "Deployment complete"
cat <<EOF
Site:   http://172.22.226.86:5174
API:    http://127.0.0.1:8808/api/v1/health (local only)
Login:  admin / API_KEY from $ENV_FILE (unless AUTH_PASSWORD is set)
AI key: set it in the web UI (AI settings) or edit $ENV_FILE and restart
Status: systemctl status backing-backend backing-frontend
Logs:   journalctl -u backing-backend -u backing-frontend -n 100 --no-pager
Data:   $ROOT/data
EOF
